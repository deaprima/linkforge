func TestResolveAlias(t *testing.T) {
	past := time.Now().Add(-time.Hour)
	active := &entity.Link{ID: uuid.New(), OriginalURL: "https://a.com", ShortCode: "abc123"}
	custom := &entity.Link{ID: uuid.New(), OriginalURL: "https://b.com", ShortCode: "def456", CustomAlias: ptr("promo")}
	expired := &entity.Link{ID: uuid.New(), OriginalURL: "https://c.com", ShortCode: "old999", ExpiredAt: &past}
	locked := &entity.Link{ID: uuid.New(), OriginalURL: "https://d.com", ShortCode: "lock11", PasswordHash: ptr("hash")}

	tests := []struct {
		name        string
		alias       string
		wantURL     string
		wantExpired bool
		wantLocked  bool
		wantClick   bool
		wantErr     string
	}{
		{"by short code", "abc123", "https://a.com", false, false, true, ""},
		{"by custom alias", "promo", "https://b.com", false, false, true, ""},
		{"expired link is flagged and not counted", "old999", "https://c.com", true, false, false, ""},
		{"password protected link is flagged but not counted before verify", "lock11", "https://d.com", false, true, false, ""},
		{"unknown alias", "nothing", "", false, false, false, "link not found"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			svc, repo, _ := newTestService(active, custom, expired, locked)
			res, err := svc.ResolveAlias(context.Background(), tt.alias, ClientInfo{})
			if tt.wantErr != "" {
				if err == nil || !strings.Contains(err.Error(), tt.wantErr) {
					t.Fatalf("want error %q, got %v", tt.wantErr, err)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			if res.OriginalURL != tt.wantURL || res.IsExpired != tt.wantExpired || res.HasPassword != tt.wantLocked {
				t.Errorf("got %+v", res)
			}

			// Click count di-increment async (fire-and-forget)
			select {
			case id := <-repo.clicked:
				if !tt.wantClick {
					t.Errorf("click counted for %s, want none", id)
				}
			case <-time.After(200 * time.Millisecond):
				if tt.wantClick {
					t.Error("click count was not incremented")
				}
			}
		})
	}
}

