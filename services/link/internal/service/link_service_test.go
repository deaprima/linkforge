func TestUpdateLink(t *testing.T) {
	owner := uuid.New()
	future := time.Now().Add(24 * time.Hour)
	later := time.Now().Add(48 * time.Hour)

	newLink := func() *entity.Link {
		return &entity.Link{ID: uuid.New(), UserID: owner, OriginalURL: "https://old.com", ShortCode: "abc123", ExpiredAt: &future}
	}

	tests := []struct {
		name    string
		input   func(id uuid.UUID) UpdateLinkInput
		wantErr string
		check   func(t *testing.T, l *LinkView)
	}{
		{
			name:    "not found for other user",
			input:   func(id uuid.UUID) UpdateLinkInput { return UpdateLinkInput{ID: id, UserID: uuid.New()} },
			wantErr: "link not found",
		},
		{
			name:    "blocked destination",
			input:   func(id uuid.UUID) UpdateLinkInput { return UpdateLinkInput{ID: id, UserID: owner, OriginalURL: "https://evil.com"} },
			wantErr: "is blocked",
		},
		{
			name:    "invalid destination",
			input:   func(id uuid.UUID) UpdateLinkInput { return UpdateLinkInput{ID: id, UserID: owner, OriginalURL: "nope"} },
			wantErr: "invalid url",
		},
		{
			name:    "reserved alias rejected",
			input:   func(id uuid.UUID) UpdateLinkInput { return UpdateLinkInput{ID: id, UserID: owner, Alias: "admin"} },
			wantErr: "is reserved",
		},
		{
			name:    "malformed alias rejected",
			input:   func(id uuid.UUID) UpdateLinkInput { return UpdateLinkInput{ID: id, UserID: owner, Alias: "a b/c"} },
			wantErr: "alias hanya boleh",
		},
		{
			name: "updates url and alias",
			input: func(id uuid.UUID) UpdateLinkInput {
				return UpdateLinkInput{ID: id, UserID: owner, OriginalURL: "https://new.com", Alias: "new-alias", ExpiredAt: &future}
			},
			check: func(t *testing.T, l *LinkView) {
				if l.OriginalURL != "https://new.com" || l.Alias != "new-alias" {
					t.Errorf("got url=%q alias=%q", l.OriginalURL, l.Alias)
				}
			},
		},
		{
			name:  "clear expiry",
			input: func(id uuid.UUID) UpdateLinkInput { return UpdateLinkInput{ID: id, UserID: owner, ClearExpiry: true} },
			check: func(t *testing.T, l *LinkView) {
				if l.ExpiredAt != nil {
					t.Errorf("expiry = %v, want nil", l.ExpiredAt)
				}
			},
		},
		{
			name:  "set new expiry",
			input: func(id uuid.UUID) UpdateLinkInput { return UpdateLinkInput{ID: id, UserID: owner, ExpiredAt: &later} },
			check: func(t *testing.T, l *LinkView) {
				if l.ExpiredAt == nil || !l.ExpiredAt.Equal(later) {
					t.Errorf("expiry = %v, want %v", l.ExpiredAt, later)
				}
			},
		},
		{
			name:  "empty fields keep existing values",
			input: func(id uuid.UUID) UpdateLinkInput { return UpdateLinkInput{ID: id, UserID: owner} },
			check: func(t *testing.T, l *LinkView) {
				if l.OriginalURL != "https://old.com" || l.Alias != "abc123" || l.ExpiredAt == nil {
					t.Errorf("fields changed unexpectedly: %+v", l)
				}
			},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			existing := newLink()
			svc, _, _ := newTestService(existing)
			got, err := svc.UpdateLink(context.Background(), tt.input(existing.ID))
			if tt.wantErr != "" {
				if err == nil || !strings.Contains(err.Error(), tt.wantErr) {
					t.Fatalf("want error %q, got %v", tt.wantErr, err)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			tt.check(t, got)
		})
	}
}

